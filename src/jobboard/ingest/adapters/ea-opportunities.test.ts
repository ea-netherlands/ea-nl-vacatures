/**
 * The page as the App Router serves it: the dataset inside RSC push chunks,
 * split mid-record across two of them, with a long description moved out into
 * a text row and a dollar-sign salary escaped as `$$`.
 */
function appRouterPage(): string {
  const longText = 'Curated two-day workshop in Berlin — for cryptographers and funders.'
  const row = (o: unknown) => JSON.stringify(o)
  const records = [
    { ...GENERATOR, description: '$1a' },
    BERKELEY_JOB,
  ]
  const stream =
    `0:["$","main",null,{}]\n` +
    `1a:T${Buffer.byteLength(longText, 'utf8').toString(16)},${longText}` +
    `2:["$","$L336",null,{"opportunities":${row(records)}}]\n`
  const cut = Math.floor(stream.length / 2)
  const push = (s: string) => `<script>self.__next_f.push(${JSON.stringify([1, s])})</script>`
  return `<html><body>${push(stream.slice(0, cut))}${push(stream.slice(cut))}</body></html>`
}

test('eaOpportunities reads the dataset out of the RSC stream and undoes its string encoding', () => {
  const opps = eaOpportunities(appRouterPage())
  assert.equal(opps.length, 2)
  assert.equal(opps[0].title, 'Generator Residency')
  // The text row, by UTF-8 byte length — the em dash is three bytes.
  assert.equal(opps[0].description, 'Curated two-day workshop in Berlin — for cryptographers and funders.')
  assert.equal(opps[1].salaryOriginal, '$160,000 – $185,000 a year')
})

test('flightTextRows measures a text row in bytes, not characters', () => {
  const rows = flightTextRows(`7:T${(9).toString(16)},café ok!3:["x"]`)
  // "café ok!" is 8 characters and 9 bytes.
  assert.equal(rows.get('7'), 'café ok!')
})

test('eaOpportunities still reads the older __NEXT_DATA__ shape', () => {
  const html = `<script id="__NEXT_DATA__" type="application/json">${JSON.stringify({
    props: { pageProps: { opportunities: [BERKELEY_JOB] } },
  })}</script>`
  assert.equal(eaOpportunities(html)[0].id, BERKELEY_JOB.id)
})

test('eaOpportunities fails loudly when the page has no dataset', () => {
  assert.throws(() => eaOpportunities('<html></html>'), /no opportunities array/)
})

test('programmes are taken wherever they are held; jobs only where a Dutch resident can do them', () => {
  assert.equal(listingKindOf(['Fellowship']), 'programme')
  assert.equal(listingKindOf(['Full-time', 'Fellowship']), 'programme')
  assert.equal(listingKindOf(['Internship']), 'job')
  assert.equal(listingKindOf(['Course']), null)
  assert.equal(listingKindOf(['Funding']), null)

  assert.equal(wanted(GENERATOR), true)
  assert.equal(wanted(BERKELEY_JOB), false)
  assert.equal(wanted({ ...BERKELEY_JOB, locationFilter: ['Remote', 'Europe (excluding UK)'] }), true)
  assert.equal(
    wanted({ ...GENERATOR, title: 'List of Recurring Fellowships Relevant to Top Problems' }),
    false,
  )
  assert.equal(
    wanted({ ...GENERATOR, applicationLink: 'https://airtable.com/app53PsYpHxJW61l3/shrQSYXSW9z96y5WE' }),
    false,
  )
})

function asStage1(listing: NonNullable<ReturnType<typeof eaOpportunitiesBoard.normalise>>): Stage1Input {
  return {
    id: 1,
    title: listing.title,
    employer_name: listing.employerName,
    location_raw: listing.locationRaw,
    country: listing.country,
    description: listing.description,
    salary_max: listing.salaryMax,
    salary_currency: listing.salaryCurrency,
    employer: null,
    listing_kind: listing.listingKind,
  }
}

test('Generator Residency normalises as a programme and passes stage one on its own page', () => {
  const listing = eaOpportunitiesBoard.normalise(
    { externalId: GENERATOR.id, payload: { ...GENERATOR, programmePage: GENERATOR_PAGE } },
    {},
  )
  assert.ok(listing)
  assert.equal(listing.listingKind, 'programme')
  assert.equal(listing.employerName, 'Kairos')
  assert.equal(listing.applyUrl, 'https://generatorresidency.org/')
  assert.equal(listing.locationRaw, 'Berkeley, CA (USA)')
  assert.equal(listing.country, 'US')
  assert.equal(listing.deadlineAt?.toISOString(), '2026-11-01T23:59:59.000Z')
  // The board carries no salary; the stipend comes from the programme's page.
  assert.equal(listing.salaryMin, 8500)
  assert.equal(listing.salaryCurrency, 'USD')
  assert.equal(listing.salaryPeriod, 'month')
  assert.doesNotMatch(listing.description ?? '', /generated by AI/)
  assert.match(listing.description ?? '', /From the programme's own page:/)

  const verdict = stage1(asStage1(listing))
  assert.equal(verdict.pass, true, verdict.pass ? '' : verdict.reason)
  if (!verdict.pass) return
  assert.match(verdict.nlReason, /paid programme of 13 weeks with travel covered/)
  assert.deepEqual(verdict.programme, { weeks: 13, paid: true, travelCovered: true })
  // A stipend is not a salary to give from.
  assert.ok(!verdict.allowedLeverage.includes('earning-to-give'))
})

test('without its own page, Generator still reaches stage two, which supplies the pay', () => {
  const listing = eaOpportunitiesBoard.normalise({ externalId: GENERATOR.id, payload: GENERATOR }, {})
  assert.ok(listing)
  const verdict = stage1(asStage1(listing))
  assert.equal(verdict.pass, true)
  if (!verdict.pass) return
  assert.match(verdict.nlReason, /does not state pay; deferring to stage two/)
  assert.deepEqual(verdict.programme, { weeks: 13, paid: null, travelCovered: null })
})

test('the same residency as a job is still dropped: the rule is for programmes only', () => {
  const listing = eaOpportunitiesBoard.normalise(
    { externalId: GENERATOR.id, payload: { ...GENERATOR, programmePage: GENERATOR_PAGE } },
    {},
  )
  assert.ok(listing)
  const verdict = stage1({ ...asStage1(listing), listing_kind: 'job' })
  assert.equal(verdict.pass, false)
})

test('an on-site Berkeley job is dropped, with its escaped salary read correctly', () => {
  const listing = eaOpportunitiesBoard.normalise({ externalId: BERKELEY_JOB.id, payload: BERKELEY_JOB }, {})
  assert.ok(listing)
  assert.equal(listing.listingKind, 'job')
  assert.equal(listing.salaryMin, 160000)
  assert.equal(listing.salaryMax, 185000)
  const verdict = stage1(asStage1(listing))
  assert.equal(verdict.pass, false)
})
